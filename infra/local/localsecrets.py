#!/usr/bin/env python3
"""Local secrets for the compose stack and CI: the stand-in for Secret Manager.

    python3 infra/local/localsecrets.py init     # create missing values (idempotent); run by `make up`
    python3 infra/local/localsecrets.py env      # print the KEY=VALUE file's path

Writes two gitignored files under <repo>/.local/ (mode 0600):
  secrets.json  Secret Manager secret name -> value; served by secretmanager.py at the same REST
                path Secret Manager uses, so the gateway reads it through its normal client
  secrets.env   KEY=VALUE for compose `env_file` (what Cloud Run injects from Secret Manager in
                production), plus the per-service database URLs

Existing values are never changed, so restarting the stack keeps the database usable. Every
generated value starts with `sclocal_`, so production code can recognise and refuse it.
Refuses to run on Cloud Run or with SHIPCUBE_ENV set to anything but `local`.
Standard library only.
"""

from __future__ import annotations

import json
import os
import re
import secrets
import sys
from pathlib import Path
from urllib.parse import quote

_HERE = Path(__file__).resolve()
ROOT = _HERE.parents[2] if len(_HERE.parents) > 2 else _HERE.parent  # repo root; /app in the container
LOCAL = Path(os.environ.get("SHIPCUBE_LOCAL_DIR", ROOT / ".local"))
PROJECT = "shipcube-control-ks"  # the Cloud SQL IAM user names bootstrap.sql grants roles to
LOCAL_PREFIX = "sclocal_"

# Secret Manager name -> how to make a local value.
GENERATED = ("token-hmac-pepper", "sql-postgres-password", "db-sc-migrator", "db-sc-api", "db-sc-worker")


def refuse_production() -> None:
    if os.environ.get("K_SERVICE") or os.environ.get("CLOUD_RUN_JOB"):
        sys.exit("local secrets refuse to run on Cloud Run")
    env = os.environ.get("SHIPCUBE_ENV", "local")
    if env != "local":
        sys.exit(f"local secrets refuse to run with SHIPCUBE_ENV={env}")


def _from_dotenv(*keys: str) -> str:
    """The Muse key, if the developer already has it in the repo's .env."""
    path = ROOT / ".env"
    if not path.exists():
        return ""
    for line in path.read_text().splitlines():
        m = re.match(r"\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)", line)
        if m and m[1] in keys:
            return m[2].strip().strip("'\"")
    return ""


def _write(path: Path, text: str) -> None:
    tmp = path.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def load() -> dict[str, str]:
    path = LOCAL / "secrets.json"
    return json.loads(path.read_text()) if path.exists() else {}


def init() -> dict[str, str]:
    refuse_production()
    LOCAL.mkdir(parents=True, exist_ok=True)
    (LOCAL / ".gitignore").write_text("*\n")  # belt and braces on top of the repo's .gitignore
    values = load()
    created = []
    for name in GENERATED:
        if not values.get(name):
            values[name] = LOCAL_PREFIX + secrets.token_urlsafe(32)
            created.append(name)
    if not values.get("meta-api-key"):
        values["meta-api-key"] = _from_dotenv("MUSE_API_KEY", "META_API_KEY")
        if values["meta-api-key"]:
            created.append("meta-api-key (from .env)")
    _write(LOCAL / "secrets.json", json.dumps(values, indent=2, sort_keys=True) + "\n")
    _write(LOCAL / "secrets.env", render_env(values))
    print(f"local secrets in {LOCAL}: " + (", ".join(created) + " created" if created else "unchanged"))
    if not values["meta-api-key"]:
        print("  meta-api-key is empty: put MUSE_API_KEY=... in .env and rerun to use the real model")
    return values


def render_env(v: dict[str, str]) -> str:
    def url(login: str, password: str) -> str:
        user = quote(f"{login}@{PROJECT}.iam", safe="")
        return f"postgresql://{user}:{quote(password, safe='')}@db:5432/shipcube"

    lines = {
        "SHIPCUBE_ENV": "local",
        "POSTGRES_PASSWORD": v["sql-postgres-password"],
        "SC_MIGRATOR_DB_PASSWORD": v["db-sc-migrator"],
        "SC_API_DB_PASSWORD": v["db-sc-api"],
        "SC_WORKER_DB_PASSWORD": v["db-sc-worker"],
        "SHIPCUBE_MIGRATOR_DATABASE_URL": url("sc-migrator", v["db-sc-migrator"]),
        "SHIPCUBE_API_DATABASE_URL": url("sc-api", v["db-sc-api"]),
        "SHIPCUBE_WORKER_DATABASE_URL": url("sc-worker", v["db-sc-worker"]),
        "SHIPCUBE_TOKEN_PEPPER": v["token-hmac-pepper"],
        "META_API_KEY": v.get("meta-api-key", ""),
    }
    return "# Generated by infra/local/localsecrets.py. Local only; never commit.\n" + "".join(
        f"{k}={val}\n" for k, val in lines.items())


def main(argv: list[str]) -> None:
    cmd = argv[1] if len(argv) > 1 else "init"
    if cmd == "init":
        init()
    elif cmd == "env":
        print(LOCAL / "secrets.env")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
